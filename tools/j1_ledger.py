"""j1_ledger.py — compute the 𝕁₁ grade of every derivation on the chart and compare with the hand-written cells.

Usage: python3 tools/j1_ledger.py [--write] [--node ID]
Writes census/j1-ledger.md (with --write), which build.py renders on the cards.
"""
from __future__ import annotations
import argparse
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import nodes as N  # noqa: E402
import licences as LC  # noqa: E402
import j1 as J  # noqa: E402

ROOT = os.path.dirname(HERE)


def compute(nodes, rng, only=None):
    import check as K
    cache, grades, rows = {}, {}, []
    for node in sorted(nodes.values(), key=lambda n: n.get("order", 0) if isinstance(n.get("order"), int) else 0):
        if node.get("level") != "object" or node.get("type") in ("gap", "import", "decree", "primitive", "definition"):
            continue
        if node.get("type") == "axiom":
            continue
        if node.get("type") == "schema":
            try:
                insts = K.schema_instances(node)
            except ValueError:
                insts = []
            tape = J.Tape()
            for inst in insts:
                t = J.grade_node(inst, nodes, cache, grades, rng, LC.check_node)
                tape.worse(t.grade)
                # keep one receipt per (rule, where, grade)
                seen = {(r.rule, r.where, r.grade, r.content) for r in tape.receipts}
                for r in t.receipts:
                    if (r.rule, r.where, r.grade, r.content) not in seen:
                        tape.receipts.append(r)
                        seen.add((r.rule, r.where, r.grade, r.content))
                tape.absent += [a for a in t.absent if a not in tape.absent]
        else:
            tape = J.grade_node(node, nodes, cache, grades, rng, LC.check_node)
        grades[node.id] = tape
        hand = (node.get("holds") or {}).get("J1", "")
        rows.append((node.id, tape, hand))
        if only and node.id == only:
            break
    return grades, rows


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--node")
    ap.add_argument("--seed", type=int, default=20261004)
    args = ap.parse_args(argv)
    nodes = N.load_nodes(os.path.join(ROOT, "nodes"))
    rng = random.Random(args.seed)
    grades, rows = compute(nodes, rng, args.node)
    agree = disagree = 0
    out = ["# 𝕁₁ ledger — computed by the receipt prover (tools/j1.py)", "",
           "Grade of each derivation in 𝕁₁ (LEGISLATION 30): ≡ strict · absorbed (receipts paid by an instance) · posted (receipts on the tape, mod Λ) · import (a unit step under a square: sound only by the reading) · absent. Generated by `python3 tools/j1_ledger.py --write`; do not edit.", "",
           "| node | computed cell | hand cell | tape |", "|---|---|---|---|"]
    for nid, tape, hand in rows:
        comp = tape.cell
        same = (comp == hand) or (hand == "holds" and comp == "holds") or (hand in ("replaced", "untested") )
        mark = "" if same else " **≠**"
        if comp == hand:
            agree += 1
        elif hand not in ("replaced", "untested"):
            disagree += 1
        out.append(f"| `{nid}` | {comp}{mark} | {hand} | {J.describe(tape).replace('|', '/')} |")
        if args.node and nid == args.node:
            print(nid, comp, hand, J.describe(tape))
    print(f"{len(rows)} derivations graded · agree {agree} · disagree {disagree} (hand cells replaced/untested not counted)")
    for nid, tape, hand in rows:
        if tape.cell != hand and hand not in ("replaced", "untested"):
            print(f"  ≠ {nid}: computed {tape.cell}, hand {hand} — {J.describe(tape)[:200]}")
    if args.write:
        path = os.path.join(ROOT, "census", "j1-ledger.md")
        open(path, "w").write("\n".join(out) + "\n")
        print("wrote", path)


if __name__ == "__main__":
    main()
