"""census.py — the small-form census (SPEC §6.2).

Enumerates every form with at most SIZE boundaries (no variables), canonicalizes,
evaluates in the ℂ reading, classifies, and assigns each form to the node that reads it.

Classes:
  numeral    a pile o…o (or the void)
  reduces    its value is already the value of some strictly smaller form
  new        a value no smaller form has
  hole       the black hole □ itself (size 1)
  excluded   contains <□> (James's exclusion)
  undefined  contains [□] (no value in ℂ; Bricken: complex infinity)

Writes census/size-le-N.md and prints the unassigned `new`/`undefined` forms, which must be
listed in census/open-forms.md (check.py enforces this).
"""
from __future__ import annotations
import itertools
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import forms as F  # noqa: E402
import nodes as N  # noqa: E402

ROOT = os.path.dirname(HERE)
SIZE = 3


def all_forms(size: int):
    """All canonical forms with exactly `size` boundaries."""
    memo = {0: {()}}

    def forms_of(n):
        if n in memo:
            return memo[n]
        out = set()
        # a form of size n is a multiset of boundaries b_1..b_k with sizes s_i >= 1 summing to n
        for parts in partitions(n):
            # choose for each part a boundary of that size: kind x inner form of size part-1
            choices = []
            for p in parts:
                opts = [(k, inner) for k in (F.ROUND, F.SQUARE, F.ANGLE) for inner in forms_of(p - 1)]
                choices.append(opts)
            for combo in itertools.product(*choices):
                out.add(F.canon(tuple(combo)))
        memo[n] = out
        return out

    result = []
    for n in range(size + 1):
        result.extend(sorted(forms_of(n), key=F.to_string))
    return result


def partitions(n, maxpart=None):
    """Integer partitions of n as non-increasing tuples."""
    if maxpart is None:
        maxpart = n
    if n == 0:
        yield ()
        return
    for p in range(min(n, maxpart), 0, -1):
        for rest in partitions(n - p, p):
            yield (p,) + rest


def classify(form, values_smaller):
    s = F.to_string(form)
    if form == () or re.fullmatch(r"(\(\)\s*)+", s):
        return "numeral", F.evaluate(form)
    if s == "[]":
        return "hole", F.BH
    try:
        v = F.evaluate(form)
    except F.Excluded:
        return "excluded", None
    except F.Undefined:
        return "undefined", None
    for w in values_smaller:
        if F.equal(v, w):
            return "reduces", v
    return "new", v


def node_assignments(nodes):
    """Map canonical form string -> node id, from each node's `forms:` list and law sides."""
    table = {}
    for nid, node in nodes.items():
        cands = list(node.get("forms", []) or [])
        law = str(node.get("law", ""))
        for part in re.split(r"≐|:=", law):
            cands.append(part.strip())
        for c in cands:
            try:
                f = F.parse(c)
            except Exception:
                continue
            if F.variables(f):
                continue
            table.setdefault(F.to_string(f), nid)
    return table


PATTERNS = [
    (re.compile(r"^(\(\)\s*)+$"), "N.numeral"),          # piles
    (re.compile(r"^<(\(\)\s*)+>$"), "Z.negative-numeral"),  # mirrored piles
    (re.compile(r"^(<\(\)>\s*)+$"), "Z.negative-numeral"),  # piles of mirrored units
]


def assign(form, cls, table):
    s = F.to_string(form)
    if form == ():
        return "void.page"
    if s in table:
        return table[s]
    for pat, nid in PATTERNS:
        if pat.match(s):
            return nid
    if cls == "excluded":
        return "mult.hole-exclusion"
    return ""


def run(size=SIZE, write=True):
    nodes = N.load_nodes(os.path.join(ROOT, "nodes"))
    table = node_assignments(nodes)
    rows = []
    values_by_size = {}
    for form in all_forms(size):
        n = F.size(form)
        smaller = [v for k, vs in values_by_size.items() if k < n for v in vs]
        cls, v = classify(form, smaller)
        if v is not None:
            values_by_size.setdefault(n, []).append(v)
        rows.append((n, form, cls, v, assign(form, cls, table)))
    unassigned = [(F.to_string(f, sugar=True), cls) for n, f, cls, v, a in rows if cls in ("new", "undefined") and not a]
    if write:
        os.makedirs(os.path.join(ROOT, "census"), exist_ok=True)
        path = os.path.join(ROOT, "census", f"size-le-{size}.md")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(f"# Census of forms with at most {size} boundaries\n\n")
            fh.write("Generated by `tools/census.py`. Every `new` or `undefined` form must be assigned to a node or listed in `open-forms.md`.\n\n")
            counts = {}
            for r in rows:
                counts[r[2]] = counts.get(r[2], 0) + 1
            fh.write("Totals: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + f" — {len(rows)} forms.\n\n")
            fh.write("| size | form | sugar | class | value | node |\n|---|---|---|---|---|---|\n")
            for n, f, cls, v, a in rows:
                val = "—" if v is None else F.fmt(v)
                fh.write(f"| {n} | `{F.to_string(f)}` | `{F.to_string(f, sugar=True)}` | {cls} | {val} | {('[[' + a + ']]') if a else ''} |\n")
        print(f"wrote {path}: {len(rows)} forms")
    return rows, unassigned


if __name__ == "__main__":
    rows, unassigned = run()
    print("unassigned new/undefined forms:")
    for s, cls in unassigned:
        print(f"  {s:20} {cls}")
